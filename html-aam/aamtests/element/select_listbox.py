# Testing: https://w3c.github.io/aria/html-aam/#el-select-listbox

TEST_HTML = "<select id='target' size='4'><option>option</option></select>"

def test_atspi(atspi, session, inline):
    session.url = inline(TEST_HTML)

    # Spec:
    # Use WAI-ARIA mapping

    node = atspi.find_node("target", session.url)
    assert atspi.Accessible.get_role(node) == atspi.Role.LIST_BOX
    assert atspi.Accessible.get_selection_iface(node) is not None

