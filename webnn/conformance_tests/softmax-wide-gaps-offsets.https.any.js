const transpose2D = (data, rows, cols) => {
  const out = new Array(data.length);
  for (let r = 0; r < rows; ++r) {
    for (let c = 0; c < cols; ++c) {
      out[c * rows + r] = data[r * cols + c];
    }
  }
  return out;
};

const softmaxTest = (name, data, shape, axis, constant, expected) => {
  const input = {'data': data, 'descriptor': {shape, dataType: 'float32'}};
  if (constant) {
    input['constant'] = true;
  }
  return {
    'name': name,
    'graph': {
      'inputs': {'softmaxInput': input},
      'operators': [{
        'name': 'softmax',
        'arguments': [{'input': 'softmaxInput'}, {'axis': axis}],
        'outputs': 'softmaxOutput'
      }],
      'expectedOutputs': {
        'softmaxOutput':
            {'data': expected, 'descriptor': {shape, dataType: 'float32'}}
      }
    }
  };
};

