//
// Conditional candidate (see README.md): only worth submitting together with a
// demonstrated violation of the existing public allowances.
//
// sqrt: the float32 neighbours of one, 1 - 2^-24 and 1 + 2^-23, whose exact
// square roots sit just below the midpoints 1 - 2^-25 and 1 + 2^-24, so a
// correctly rounded result is 1 - 2^-24 and 1.0 respectively; the smallest
// standalone input of the existing corpus (0.09894), the smallest normal
// float32 (2^-126, whose root 2^-63 is exact) and the exact square 4.0.
// Inputs are written as the float32 values nearest the decimal literals.
// References via integer square roots at 2^-200 resolution with a check that
// both bracketing rationals round to the same binary32; see
// derive_references.py. The allowance is the standalone sqrt file's 1 ULP.
//
// reduceMean: 576 elements (the SmolLM2 hidden size; 576 = 2^6 * 9, so the
// divisor is not a power of two) on a 1/1024 grid in [-2, 2), MINSTD seed
// 20261028, chosen so that the exact sum -10855/512 gives the mean
// -10855/294912, which is not representable and must be rounded. The
// allowance is the utils.js reduceMean entry, R + 2 = 578 ULP.

const getSqrtOrReduceMeanPrecisionTolerance =
    (graphResources, intermediateOperands) => {
      if (graphResources.operators[0].name === 'sqrt') {
        // Same allowance as sqrt.https.any.js.
        return {metricType: 'ULP', value: 1};
      }
      // reduceMean: R + 2 from utils.js.
      return getPrecisionTolerance(graphResources, intermediateOperands);
    };

