# Testing: https://w3c.github.io/aria/html-aam/#el-meter

TEST_HTML = "<meter id='target' value='0.5'></meter>"

def test_atspi(atspi, session, inline):
    session.url = inline(TEST_HTML)

    # Spec:
    # Use WAI-ARIA mapping

    node = atspi.find_node("target", session.url)
    assert atspi.Accessible.get_role(node) == atspi.Role.LEVEL_BAR
    assert atspi.Accessible.get_value_iface(node) is not None

