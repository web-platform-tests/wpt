def test_up_tick_waits_for_click_before_same_source_far_tap(
    session, inline, configuration, new_tab_classic, touch_chain, variant
):
    """P7: the click of a tap is dispatched before a later tap elsewhere.

    The same question as P6, for remote ends that don't support key input
    alongside touch input. The moves have an explicit duration of 0, so the
    time between the taps isn't what decides the result: if it were longer
    than a double-tap window, the first click would be dispatched before the
    second tap even if the command didn't wait for it. The summary's "tap gap"
    shows the time between them.
    """
    target = load_gesture_page(session, inline, variant)
    target2 = session.find.css("#target2", all=False)
    touch_chain.pointer_move(0, 0, duration=0, origin=target) \
        .pointer_down().pointer_up() \
        .pointer_move(0, 0, duration=0, origin=target2) \
        .pointer_down().pointer_up()

    at_return, eventually, duration = observe(
        session, configuration,
        lambda: perform_actions(session, configuration, [touch_chain.dict]))

    assert dispatched_before(
        eventually, ("click", "target", 0), ("pointerdown", "target2", 0)), \
        describe(at_return, eventually, duration)


def test_up_tick_waits_for_click_before_same_source_double_tap(
    session, inline, configuration, new_tab_classic, touch_chain, variant
):
    """P8: the click of a tap is dispatched before a second tap at the same point.

    Distinguishes waiting for the click per tick (C1) from looking ahead to
    the second tap (E). Waiting means a double tap can't be expressed within a
    single command when the user agent has a double-tap window.
    """
    target = load_gesture_page(session, inline, variant)
    scale = visual_scale(session)
    touch_chain.click(element=target).pointer_down().pointer_up()

    at_return, eventually, duration = observe(
        session, configuration,
        lambda: perform_actions(session, configuration, [touch_chain.dict]))

    assert dispatched_before(
        eventually, ("click", "target", 0), ("pointerdown", "target", 1)), \
        describe(at_return, eventually, duration,
                 scale_before=scale, scale_after=visual_scale(session))


def test_separate_commands_tap_not_combined(
    session, inline, configuration, new_tab_classic, touch_chain, variant
):
    """P9: taps in two consecutive commands aren't recognised as a double tap.

    Also related to https://github.com/w3c/webdriver/issues/1772.
    """
    target = load_gesture_page(session, inline, variant)
    scale = visual_scale(session)
    touch_chain.click(element=target)

    def perform():
        perform_actions(session, configuration, [touch_chain.dict])
        perform_actions(session, configuration, [touch_chain.dict])

    at_return, eventually, duration = observe(session, configuration, perform)
    scale_after = visual_scale(session)
    message = describe(at_return, eventually, duration,
                       scale_before=scale, scale_after=scale_after)

    assert count(eventually, "click", "target") == 2, message
    assert count(eventually, "dblclick") == 0, message
    assert scale_after == scale, message


