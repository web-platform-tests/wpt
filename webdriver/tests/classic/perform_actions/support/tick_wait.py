def test_click_before_return_with_slow_pointerup_handler(
    session, inline, configuration, new_tab_classic, touch_chain, variant
):
    """P11: the click is dispatched before return even if pointerup is slow.

    The page blocks its main thread for 150ms in its pointerup and touchend
    handlers, which holds up what a user agent does after them, such as the
    gesture recogniser's click. A remote end that waits for recogniser
    outcomes that can be resolved immediately (C2) returns after the click; one
    that only waits for the events the input produces directly (A) may return
    before it. Most informative in variants without a tap delay. If the user
    agent dispatches the click in the same task as touchend, A and C2 can't be
    told apart.
    """
    target = load_gesture_page(
        session, inline, variant,
        script=slow_handler_script(["pointerup", "touchend"]))
    touch_chain.click(element=target)

    at_return, eventually, duration = observe(
        session, configuration,
        lambda: perform_actions(session, configuration, [touch_chain.dict]))

    assert count(at_return, "click", "target") == 1, \
        describe(at_return, eventually, duration)


def test_pan_cancel_before_return_with_slow_pointermove_handler(
    session, inline, configuration, new_tab_classic, touch_chain, variant
):
    """P12: a pointercancel from a pan is dispatched before return even if pointermove is slow.

    As P11, for a user agent taking over the pointer for a pan, which it can
    decide immediately. The first pointermove blocks the page for 150ms.
    Nothing is asserted if the user agent doesn't cancel at all.
    """
    if variant == "touch-action-none":
        pytest.skip("touch-action: none stops the user agent taking over a pan")

    load_gesture_page(
        session, inline, variant,
        extra_css="body { height: 3000px; }",
        script=slow_handler_script(["pointermove"], once=True))
    # Start far enough down the page that moving up stays inside the viewport.
    target2 = session.find.css("#target2", all=False)
    touch_chain.pointer_move(0, 0, origin=target2) \
        .pointer_down() \
        .pointer_move(0, -150, duration=300, origin="pointer") \
        .pointer_up()

    at_return, eventually, duration = observe(
        session, configuration,
        lambda: perform_actions(session, configuration, [touch_chain.dict]))

    assert count(at_return, "pointercancel") == count(eventually, "pointercancel"), \
        describe(at_return, eventually, duration)
